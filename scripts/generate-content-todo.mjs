#!/usr/bin/env node
/**
 * Regenerates CONTENT-TODO.md from what is actually in the tree.
 *
 * A hand-maintained list of placeholders goes stale the first time someone
 * fills one in and forgets to cross it off, which makes it worse than useless:
 * it tells you the site is more finished than it is. This reads the source.
 *
 * Run: npm run content:todo
 *
 * It counts real placeholder VALUES only -- a frontmatter field or a string
 * literal whose value starts with `TODO:`. Comments and prose that merely
 * mention the word are skipped, which is why src/data/site.ts's own header
 * and the layout's banner text do not appear in the output.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'CONTENT-TODO.md';

/** Files whose job is to describe placeholders rather than contain them. */
const SKIP = new Set([
  'CONTENT-TODO.md',
  'CONTENT-INTAKE.md',
  'CONTENT.md',
  'README.md',
  'src/content.config.ts',
  'src/components/Todo.astro',
  'src/components/Field.astro',
  'scripts/generate-content-todo.mjs',
]);

/** `key: "TODO: ..."` in YAML frontmatter, or `key: 'TODO: ...'` in TypeScript. */
const FIELD = /^\s*([A-Za-z_][\w.]*)\s*:\s*['"]TODO:\s*(.*?)['"],?\s*$/;
/** A bare continued string literal, e.g. a value wrapped to the next line. */
const BARE = /^\s*['"]TODO:\s*(.*?)['"],?\s*$/;

function tracked() {
  return execFileSync('git', ['ls-files', '-z'], { encoding: 'utf8' })
    .split('\0')
    .filter(Boolean)
    .filter((f) => /\.(md|ts|astro)$/.test(f))
    .filter((f) => !SKIP.has(f))
    .sort();
}

/** A `key:` line with the value wrapped onto the next one. */
const KEY_ONLY = /^\s*([A-Za-z_][\w.]*)\s*:\s*$/;

const found = [];

for (const file of tracked()) {
  const lines = readFileSync(file, 'utf8').split('\n');
  // Reset per file, and track the key a wrapped value belongs to, so a value
  // on its own line is not attributed to whatever field came before it.
  let lastFieldName = null;
  lines.forEach((line, i) => {
    // Skip comment lines: they discuss placeholders, they are not placeholders.
    const t = line.trim();
    if (t.startsWith('*') || t.startsWith('//') || t.startsWith('/*') || t.startsWith('#')) return;

    const k = KEY_ONLY.exec(line);
    if (k) {
      lastFieldName = k[1];
      return;
    }

    const m = FIELD.exec(line);
    if (m) {
      lastFieldName = m[1];
      found.push({ file, line: i + 1, field: m[1], prompt: m[2] });
      return;
    }
    const b = BARE.exec(line);
    if (b) {
      found.push({ file, line: i + 1, field: lastFieldName ?? '(continued)', prompt: b[1] });
    }
  });
}

// Group by file for a readable document.
const byFile = new Map();
for (const f of found) {
  if (!byFile.has(f.file)) byFile.set(f.file, []);
  byFile.get(f.file).push(f);
}

const today = new Date().toISOString().slice(0, 10);

let out = `# Placeholders still in the build

Generated by \`npm run content:todo\` on ${today}. Do not edit by hand; rerun it.

**${found.length} placeholder${found.length === 1 ? '' : 's'}** remain across ${byFile.size} file${byFile.size === 1 ? '' : 's'}.

Every one of these renders visibly on the live page as a yellow dashed box. The
site must not be pointed at pack662nyc.com until at least the Home, Meetings,
Join, and Resources entries below are filled. See CONTENT-INTAKE.md for what
each field is asking for.

`;

for (const [file, items] of byFile) {
  out += `## \`${file}\`\n\n`;
  out += `| Line | Field | Needs |\n|---|---|---|\n`;
  for (const it of items) {
    out += `| ${it.line} | \`${it.field}\` | ${it.prompt.replace(/\|/g, '\\|')} |\n`;
  }
  out += '\n';
}

out += `---

When this file reports 0 placeholders, the remaining launch steps are:

1. Remove \`<meta name="robots" content="noindex, nofollow">\` from \`src/layouts/BaseLayout.astro\`.
2. Remove the \`Disallow: /\` from \`public/robots.txt\`.
3. Set \`contentIncomplete = false\` in \`src/layouts/BaseLayout.astro\` to drop the construction banner.
4. Only then point DNS. See README, "Going live".
`;

writeFileSync(OUT, out);
console.log(`  Wrote ${OUT}: ${found.length} placeholders across ${byFile.size} files.`);
